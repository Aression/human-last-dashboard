import type { Claim, Evidence, Source } from "@/lib/types";
import { formatDate, provenanceLabel, sourceTierLabel, sourceTypeLabel } from "@/lib/labels";
import { DemoTag } from "./chips";
import { SectionTitle } from "./PageHeader";

/**
 * What a record is made of, taken only from the fields it actually stores.
 * A field that is missing is shown as missing: no URL, retrieval time, hash, or
 * snapshot is ever implied to exist for a record that does not carry one.
 * See AGENTS.md rules 2, 3 and 10 and docs/evidence-model.md.
 */
type ProvenanceRecord =
  | { kind: "evidence"; record: Evidence }
  | { kind: "claim"; record: Claim }
  | { kind: "source"; record: Source };

function Row({ label, children }: { label: string; children: React.ReactNode }) {
  return (
    <div>
      <dt className="text-xs text-muted">{label}</dt>
      <dd className="mt-0.5 text-[14px] leading-6">{children}</dd>
    </div>
  );
}

/** The only styling a missing value gets: readable, and unmistakably absent. */
function NotRecorded({ children }: { children: React.ReactNode }) {
  return <span className="text-muted italic">{children}</span>;
}

const DEMO_NOTE =
  "Fictional demonstration record: the source, publisher, authors, and the recorded dates were " +
  "invented to exercise the interface. No URL, content hash, or snapshot was ever observed for it.";

/**
 * What a given record does not establish. Shown for every record so the panel
 * cannot be read as a verification badge (AGENTS.md rules 3 and 4).
 */
const doesNotEstablish: Record<ProvenanceRecord["kind"], string> = {
  evidence:
    "It reports one observation and the method that produced it. It does not establish that the " +
    "observation reproduces, that it holds outside the conditions recorded above, that the method " +
    "was executed as described, or that any claim it is linked to is true. Review status is the " +
    "only review this system records: an unreviewed record has had none, and acceptance is a " +
    "reviewer's judgement rather than a measurement.",
  claim:
    "It records what a source asserts and where in the source the assertion appears. It does not " +
    "establish that the statement is true, that the source is authoritative, or that the " +
    "extraction is faithful to the source. A claim with no linked evidence is still a lead.",
  source:
    "It is a pointer to an artefact plus what this system captured about it. It does not establish " +
    "that the artefact exists, that its content matches this record, or that its publisher is " +
    "correct. A primary tier says who produced it, not that it is independent or validated: a " +
    "developer-affiliated source reports what the developer reports.",
};

export function ProvenancePanel(props: ProvenanceRecord) {
  const { record } = props;
  const demo = record.provenance === "demo";

  return (
    <section className="space-y-3">
      <SectionTitle title="Provenance" aside={provenanceLabel[record.provenance]} />
      <div className="max-w-3xl rounded-lg border border-line bg-surface p-4">
        {demo && (
          <p className="demo-hatch mb-4 rounded-md border border-warn/40 px-3 py-2 text-[13px] leading-6 text-warn">
            {DEMO_NOTE}
          </p>
        )}

        <dl className="grid gap-4 sm:grid-cols-2">
          <Row label="Record id">
            <code className="font-mono text-xs">{record.id}</code>
          </Row>
          <Row label="Provenance">
            <span className="inline-flex flex-wrap items-center gap-1.5">
              <span>{provenanceLabel[record.provenance]}</span>
              {demo && <DemoTag />}
            </span>
          </Row>
          <Row label="Created">{formatDate(record.created_at)}</Row>
          <Row label="Generated by">
            {record.generated_by ? (
              <span>
                {record.generated_by.model} · workflow{" "}
                <code className="font-mono text-xs">{record.generated_by.workflow_version}</code>
              </span>
            ) : (
              <NotRecorded>Not recorded — no model or workflow attribution on this record.</NotRecorded>
            )}
          </Row>

          {props.kind === "source" && (
            <>
              <Row label="Publisher">{props.record.publisher}</Row>
              <Row label="Authors">
                {props.record.authors.length > 0 ? (
                  props.record.authors.join(", ")
                ) : (
                  <NotRecorded>None recorded</NotRecorded>
                )}
              </Row>
              <Row label="Published">
                {props.record.published_at ? (
                  formatDate(props.record.published_at)
                ) : (
                  <NotRecorded>Not recorded</NotRecorded>
                )}
              </Row>
              <Row label="Canonical URL">
                {props.record.canonical_url ? (
                  <a
                    href={props.record.canonical_url}
                    target="_blank"
                    rel="noopener noreferrer"
                    className="break-all underline underline-offset-4 hover:text-ink"
                  >
                    {props.record.canonical_url}
                  </a>
                ) : (
                  <NotRecorded>Not observed — no URL is stored for this source.</NotRecorded>
                )}
              </Row>
              <Row label="Retrieved at">
                {props.record.retrieved_at ? (
                  formatDate(props.record.retrieved_at)
                ) : (
                  <NotRecorded>Not observed — this system captured no retrieval time.</NotRecorded>
                )}
              </Row>
              <Row label="Content hash">
                {props.record.content_hash ? (
                  <code className="font-mono text-xs">{props.record.content_hash}</code>
                ) : (
                  <NotRecorded>Not recorded — no hash of captured content.</NotRecorded>
                )}
              </Row>
              <Row label="Snapshot">
                <NotRecorded>
                  Not recorded — this dataset stores no snapshot reference for any source.
                </NotRecorded>
              </Row>
              <Row label="Status">{props.record.status}</Row>
              <Row label="Source type">{sourceTypeLabel[props.record.source_type]}</Row>
              <Row label="Source tier">{sourceTierLabel[props.record.source_tier]}</Row>
              <Row label="Developer-affiliated">
                {props.record.developer_affiliated
                  ? "Yes — the reporting party built or operates the system described."
                  : "No"}
              </Row>
            </>
          )}
        </dl>

        <p className="mt-4 border-t border-line pt-3 text-[13px] leading-6 text-muted">
          <span className="text-ink">What this record does not establish.</span>{" "}
          {doesNotEstablish[props.kind]}
        </p>
      </div>
    </section>
  );
}
